#!/usr/bin/env python3
"""Per-instance build generator for `signal-lock`.

Emits src/signal-lock.c with the ASP-mini bytecode program and expected[] table
baked from the chosen flag. Run at build/deploy time:

    python3 gen.py --flag "AURA{...}" > signal-lock.c

Then compile:  gcc -O2 -s -o signal-lock signal-lock.c

The transform/assembler here are byte-identical to ctf/common/asp_reference.py,
which is validated (invertibility over all inputs, VM accept/reject, solver
round-trip). Keep them in sync; CI runs solve.py against the built binary.
"""
import argparse, sys

MASK = 0xFF
K1, K2, K3 = 0x5A, 0x1B, 0x3C          # baked-in constants (solver must recover)
OP_HALT, OP_MOV, OP_MOVI = 0x00, 0x01, 0x02

def rol8(v, n): n &= 7; return ((v << n) | (v >> (8 - n))) & MASK

def transform(c, i):
    u = c ^ K1
    u = rol8(u, i & 7)
    u = (u + (i * K2)) & MASK
    return u ^ K3

def assemble(n):
    R0, INPUT, CHECK = 0x00, 0x10, 0x11
    p = []
    for i in range(n):
        p += [OP_MOV,  R0,   INPUT]
        p += [OP_MOV,  0xB0, R0]; p += [OP_MOVI, 0xB1, K1]; p += [OP_MOV, R0, 0xB2]
        p += [OP_MOV,  0xC0, R0]; p += [OP_MOVI, 0xC1, i & 7]; p += [OP_MOV, R0, 0xC2]
        p += [OP_MOV,  0xA0, R0]; p += [OP_MOVI, 0xA1, (i*K2)&MASK]; p += [OP_MOV, R0, 0xA2]
        p += [OP_MOV,  0xB0, R0]; p += [OP_MOVI, 0xB1, K3]; p += [OP_MOV, R0, 0xB2]
        p += [OP_MOV,  CHECK, R0]
    p += [OP_HALT]
    return bytes(p)

def carr(name, data):
    body = ",".join(str(b) for b in data)
    return f"static const unsigned char {name}[] = {{{body}}};\n"

C_TEMPLATE = r'''/* signal-lock : AURA-7 ASP-mini verifier (auto-generated by gen.py) */
#include <stdio.h>
#include <string.h>

%PROG%
%EXPECTED%

static unsigned char rol8(unsigned char v, int n){ n &= 7; return (unsigned char)((v<<n)|(v>>(8-n))); }

int main(void){
    unsigned char reg[256]; memset(reg, 0, sizeof reg);
    unsigned char aADD=0,aXOR=0,aROL=0, rADD=0,rXOR=0,rROL=0;
    unsigned char in[256];
    if(!fgets((char*)in, sizeof in, stdin)){ puts("nope."); return 1; }
    size_t inlen = strlen((char*)in);
    while(inlen && (in[inlen-1]=='\n' || in[inlen-1]=='\r')) in[--inlen]=0;

    size_t incur=0, outcur=0, pc=0; int fail=0;
    const size_t proglen=sizeof prog, explen=sizeof expected;
    while(pc < proglen){
        unsigned char op=prog[pc];
        if(op==0x00) break;                 /* HALT */
        unsigned char dst=prog[pc+1], src=prog[pc+2], val;
        if(op==0x01){                        /* MOV dst,src */
            if(src==0x10){ if(incur>=inlen){fail=1; val=0;} else val=in[incur++]; }
            else if(src==0xA2) val=rADD;
            else if(src==0xB2) val=rXOR;
            else if(src==0xC2) val=rROL;
            else val=reg[src];
        } else if(op==0x02){ val=src; }      /* MOVI dst,imm (src field = imm) */
        else { puts("nope."); return 1; }
        if(dst==0x11){ if(outcur>=explen || val!=expected[outcur]) fail=1; outcur++; }
        else if(dst==0xA0) aADD=val;
        else if(dst==0xA1) rADD=(unsigned char)(aADD+val);
        else if(dst==0xB0) aXOR=val;
        else if(dst==0xB1) rXOR=(unsigned char)(aXOR^val);
        else if(dst==0xC0) aROL=val;
        else if(dst==0xC1) rROL=rol8(aROL, val);
        else reg[dst]=val;
        pc+=3;
    }
    if(!fail && incur==inlen && outcur==explen){
        puts("ASP unlocked. The input you just entered is the flag.");
        return 0;
    }
    puts("nope.");
    return 1;
}
'''

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flag", default="AURA{tta_s1gnal_l0ck}")
    a = ap.parse_args()
    fb = a.flag.encode()
    prog = assemble(len(fb))
    expected = bytes(transform(c, i) for i, c in enumerate(fb))
    c = (C_TEMPLATE
         .replace("%PROG%", carr("prog", prog))
         .replace("%EXPECTED%", carr("expected", expected)))
    sys.stdout.write(c)
    sys.stderr.write(f"[gen] flag={a.flag!r} len={len(fb)} prog={len(prog)}B expected={expected.hex()}\n")

if __name__ == "__main__":
    main()
